import { mkdir, readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const SITE_BASE = "https://riaevangelist.github.io/RIAEvangelist";
const GENERATED_MARKER = "<!-- Generated by scripts/generate-story-pages.mjs. Do not edit directly. -->";
const CHECK_MODE = process.argv.includes("--check");

function escapeHtml(value) {
  return String(value ?? "")
    .replaceAll("&", "&amp;")
    .replaceAll("<", "&lt;")
    .replaceAll(">", "&gt;")
    .replaceAll('"', "&quot;")
    .replaceAll("'", "&#39;");
}

function header(prefix, current = "story") {
  const links = [
    ["home", prefix, "Home"],
    ["music", `${prefix}music/`, "Music"],
    ["story", `${prefix}story/`, "Story"]
  ].map(([key, href, label]) => `<a href="${href}"${current === key ? ' aria-current="page"' : ""}>${label}</a>`).join("\n");
  return `<header class="site-header page-site-header">
    <a class="brand" href="${prefix}" aria-label="RIAEvangelist home"><span class="brand-mark" aria-hidden="true">R//A</span><span>RIAEvangelist</span></a>
    <nav class="page-nav" aria-label="Primary navigation">${links}<a class="github-link" href="https://github.com/RIAEvangelist">GitHub ↗</a></nav>
  </header>`;
}

function layout({ prefix, title, description, canonicalPath, body, image = "" }) {
  const canonical = `${SITE_BASE}/${canonicalPath}`.replace(/\/+$/, "/");
  const imageTags = image ? `
    <meta property="og:image" content="${escapeHtml(image)}">
    <meta name="twitter:image" content="${escapeHtml(image)}">` : "";
  return `${GENERATED_MARKER}
<!doctype html>
<html lang="en">
  <head>
    <meta charset="utf-8">
    <meta name="viewport" content="width=device-width, initial-scale=1">
    <meta name="description" content="${escapeHtml(description)}">
    <meta property="og:type" content="website">
    <meta property="og:title" content="${escapeHtml(title)}">
    <meta property="og:description" content="${escapeHtml(description)}">
    <meta property="og:url" content="${canonical}">${imageTags}
    <meta name="twitter:card" content="${image ? "summary_large_image" : "summary"}">
    <meta name="twitter:title" content="${escapeHtml(title)}">
    <meta name="twitter:description" content="${escapeHtml(description)}">
    <link rel="canonical" href="${canonical}">
    <link rel="icon" href="${prefix}assets/favicon.svg" type="image/svg+xml">
    <link rel="stylesheet" href="${prefix}styles.css">
    <link rel="stylesheet" href="${prefix}pages.css">
    <title>${escapeHtml(title)}</title>
  </head>
  <body class="subpage-body">
    <a class="skip-link" href="#main">Skip to content</a>
    ${header(prefix)}
    <main id="main" class="subpage-main">${body}</main>
    <footer class="page-footer"><p>Music, software, motion, and human stories.</p><p><a href="${prefix}music/">Music</a><a href="${prefix}story/">Story</a><a href="https://github.com/RIAEvangelist">GitHub ↗</a></p></footer>
  </body>
</html>
`;
}

function storyCard(page, prefix) {
  return `<a class="story-gateway" href="${prefix}story/${page.slug}/">
    <span class="eyebrow">${escapeHtml(page.eyebrow)}</span>
    <strong>${escapeHtml(page.title)}</strong>
    <small>${escapeHtml(page.lede)}</small>
    <b>Open chapter →</b>
  </a>`;
}

function storyHub(story) {
  const prefix = "../";
  const body = `
    <section class="subpage-hero story-hero">
      <div><p class="eyebrow">The story beyond the telemetry</p><h1 class="page-title">One life.<br><span>Focused chapters.</span></h1><p class="page-lede">${escapeHtml(story.description)}</p></div>
      <dl class="page-metrics"><div><dt>Chapters</dt><dd>${story.pages.length}</dd></div><div><dt>Format</dt><dd>Short pages</dd></div><div><dt>Sources</dt><dd>Linked</dd></div></dl>
    </section>
    <section class="section-shell compact-section" aria-labelledby="story-paths-title">
      <div class="section-heading compact-heading"><div><p class="eyebrow">Choose a chapter</p><h2 id="story-paths-title">Less scrolling. More paths.</h2></div><p>Each chapter keeps one part of the story focused, sourced, and easy to share.</p></div>
      <div class="story-gateway-grid">${story.pages.map((page) => storyCard(page, prefix)).join("\n")}</div>
    </section>`;
  return layout({ prefix, title: "Story // RIAEvangelist", description: story.description, canonicalPath: "story/", image: `${SITE_BASE}/assets/og.png`, body });
}

function sourceLinks(links) {
  if (!links.length) return "";
  return `<div class="source-card-grid">${links.map((link) => `<a class="source-card" href="${escapeHtml(link.url)}" target="_blank" rel="noopener noreferrer"><strong>${escapeHtml(link.label)}</strong><small>${escapeHtml(link.note)}</small><span>Open source ↗</span></a>`).join("\n")}</div>`;
}

function storyPage(page) {
  const prefix = "../../";
  const body = `
    <section class="subpage-hero short-hero story-detail-hero">
      <div><p class="breadcrumbs"><a href="../">Story</a> / ${escapeHtml(page.eyebrow)}</p><p class="eyebrow">${escapeHtml(page.eyebrow)}</p><h1 class="page-title">${escapeHtml(page.title)}</h1><p class="page-lede">${escapeHtml(page.lede)}</p></div>
      <dl class="page-metrics">${page.facts.map((fact) => `<div><dt>${escapeHtml(fact.label)}</dt><dd>${escapeHtml(fact.value)}</dd></div>`).join("\n")}</dl>
    </section>
    <section class="story-sections" aria-label="${escapeHtml(page.title)} chapters">
      ${page.sections.map((section, index) => `<article class="story-section">
        <header><b>${String(index + 1).padStart(2, "0")}</b><div><p class="eyebrow">${escapeHtml(section.kicker)}</p><h2>${escapeHtml(section.title)}</h2></div></header>
        <div class="story-copy">${section.body.map((paragraph) => `<p>${escapeHtml(paragraph)}</p>`).join("\n")}${sourceLinks(section.links)}</div>
      </article>`).join("\n")}
    </section>
    <nav class="chapter-nav" aria-label="More story chapters"><a href="../">All chapters</a><a href="${prefix}music/">Music catalog</a><a href="${prefix}">Live telemetry</a></nav>`;
  return layout({ prefix, title: `${page.title} // RIAEvangelist`, description: page.lede, canonicalPath: `story/${page.slug}/`, body });
}

function validate(story) {
  const slugs = new Set();
  if (story.pages.length !== 5) throw new Error(`Expected 5 story pages, found ${story.pages.length}`);
  for (const page of story.pages) {
    if (!/^[a-z0-9]+(?:-[a-z0-9]+)*$/.test(page.slug) || slugs.has(page.slug)) throw new Error(`Invalid or duplicate story slug: ${page.slug}`);
    slugs.add(page.slug);
    if (!page.sections.length || !page.facts.length) throw new Error(`Incomplete story page: ${page.slug}`);
    for (const section of page.sections) for (const link of section.links) if (!/^https:\/\//.test(link.url)) throw new Error(`Unsafe story URL: ${page.slug}`);
  }
}

async function writePage(relativePath, html, generated, drift) {
  const destination = path.join(ROOT, relativePath);
  generated.push(relativePath.replaceAll("\\", "/"));
  if (CHECK_MODE) {
    if (await readFile(destination, "utf8").catch(() => null) !== html) drift.push(relativePath);
    return;
  }
  await mkdir(path.dirname(destination), { recursive: true });
  if (await readFile(destination, "utf8").catch(() => null) !== html) await writeFile(destination, html, "utf8");
}

async function main() {
  const story = JSON.parse(await readFile(path.join(ROOT, "data", "story.json"), "utf8"));
  validate(story);
  const generated = [];
  const drift = [];
  await writePage("story/index.html", storyHub(story), generated, drift);
  for (const page of story.pages) await writePage(`story/${page.slug}/index.html`, storyPage(page), generated, drift);
  const manifestPath = path.join(ROOT, "story", ".generated-pages.json");
  const manifest = `${JSON.stringify({ generated }, null, 2)}\n`;
  if (CHECK_MODE) {
    if (await readFile(manifestPath, "utf8").catch(() => null) !== manifest) drift.push("story/.generated-pages.json");
    if (drift.length) throw new Error(`Generated story pages are stale:\n${drift.map((item) => `- ${item}`).join("\n")}`);
    console.log(`Verified ${generated.length} story pages.`);
    return;
  }
  if (await readFile(manifestPath, "utf8").catch(() => null) !== manifest) await writeFile(manifestPath, manifest, "utf8");
  console.log(`Generated ${generated.length} story pages.`);
}

await main();
