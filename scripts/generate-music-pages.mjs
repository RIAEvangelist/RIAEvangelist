function pagination(page, pageCount, prefix) {
  if (pageCount <= 1) return "";
  const items = Array.from({ length: pageCount }, (_, index) => {
    const value = index + 1;
    const href = value === 1 ? `${prefix}music/releases/` : `${prefix}music/releases/page/${value}/`;
    return `<a href="${href}"${value === page ? ' aria-current="page"' : ""}>${value}</a>`;
  }).join("");
  return `<nav class="pagination" aria-label="Release catalog pages">${items}</nav>`;
}

function releasesPage(catalog, page) {
  const pageCount = Math.max(1, Math.ceil(catalog.releases.length / PAGE_SIZE));
  const releases = catalog.releases.slice((page - 1) * PAGE_SIZE, page * PAGE_SIZE);
  const prefix = page === 1 ? "../../" : "../../../../";
  const canonicalPath = page === 1 ? "music/releases/" : `music/releases/page/${page}/`;
  const body = `
    <section class="subpage-hero short-hero">
      <div><p class="breadcrumbs"><a href="${prefix}music/">Music</a> / Releases</p><p class="eyebrow">Catalog page ${page} of ${pageCount}</p><h1 class="page-title">Every release.<br><span>One at a time.</span></h1><p class="page-lede">A complete, paginated index. Each release opens into its own focused listening workspace.</p></div>
    </section>
    <section class="section-shell compact-section">
      <div class="release-grid">${releases.map((release) => releaseCard(release, prefix)).join("\n")}</div>
      ${pagination(page, pageCount, prefix)}
    </section>`;

  return { prefix, canonicalPath, html: layout({
    prefix,
    title: `Music releases — page ${page} // RIAEvangelist`,
    description: `Page ${page} of the complete AI Wizard and Brandon Nozaki Miller music catalog.`,
    canonicalPath,
    body
  }) };
}

