function escapeHtml(value) {
  return String(value ?? "")
    .replaceAll("&", "&amp;")
    .replaceAll("<", "&lt;")
    .replaceAll(">", "&gt;")
    .replaceAll('"', "&quot;")
    .replaceAll("'", "&#39;");
}

function formatDate(value) {
  return new Intl.DateTimeFormat("en-US", {
    month: "long",
    day: "numeric",
    year: "numeric",
    timeZone: "UTC"
  }).format(new Date(`${value}T00:00:00Z`));
}

function releaseHref(release, prefix) {
  return `${prefix}music/releases/${release.slug}/`;
}

function platformLinks(release, prefix, compact = false) {
  const links = release.services.map(({ service, url }) => {
    const definition = serviceDefinitions[service];
    if (!definition) throw new Error(`Unknown music service: ${service}`);
    const iconUrl = definition.localIcon
      ? `${prefix}${definition.localIcon}`
      : `https://cdn.simpleicons.org/${definition.icon}/${definition.color}`;
    return `<a class="service-link${compact ? " service-link-compact" : ""}" href="${escapeHtml(url)}" target="_blank" rel="noopener noreferrer" aria-label="Listen to ${escapeHtml(release.title)} on ${definition.label}">
      <img src="${iconUrl}" alt="" width="20" height="20" loading="lazy">
      <span>${escapeHtml(definition.label)}</span>
    </a>`;
  }).join("\n");

  return `<div class="service-links" aria-label="Listening services">${links}</div>`;
}

function header(prefix, current) {
  const nav = [
    ["home", prefix, "Home"],
    ["music", `${prefix}music/`, "Music"],
    ["story", `${prefix}story/`, "Story"]
  ].map(([key, href, label]) => `<a href="${href}"${current === key ? ' aria-current="page"' : ""}>${label}</a>`).join("\n");

  return `<header class="site-header page-site-header">
    <a class="brand" href="${prefix}" aria-label="RIAEvangelist home">
      <span class="brand-mark" aria-hidden="true">R//A</span>
      <span>RIAEvangelist</span>
    </a>
    <nav class="page-nav" aria-label="Primary navigation">
      ${nav}
      <a class="github-link" href="https://github.com/RIAEvangelist">GitHub ↗</a>
    </nav>
  </header>`;
}

function footer(prefix) {
  return `<footer class="page-footer">
    <p>Music, software, motion, and human stories.</p>
    <p><a href="${prefix}music/">Music</a><a href="${prefix}story/">Story</a><a href="https://www.youtube.com/@AI-Wizard-Music">AI Wizard ↗</a></p>
  </footer>`;
}

function layout({ prefix, title, description, canonicalPath, image, current = "music", body, openGraphType = "website", headExtra = "" }) {
  const canonical = `${SITE_BASE}/${canonicalPath}`.replace(/\/+$/, "/");
  const imageTags = image ? `
    <meta property="og:image" content="${escapeHtml(image)}">
    <meta name="twitter:image" content="${escapeHtml(image)}">` : "";
  const extraHead = headExtra ? `    ${headExtra}\n` : "";

  return `${GENERATED_MARKER}
<!doctype html>
<html lang="en">
  <head>
    <meta charset="utf-8">
    <meta name="viewport" content="width=device-width, initial-scale=1">
    <meta name="description" content="${escapeHtml(description)}">
    <meta property="og:type" content="${openGraphType}">
    <meta property="og:title" content="${escapeHtml(title)}">
    <meta property="og:description" content="${escapeHtml(description)}">
    <meta property="og:url" content="${canonical}">${imageTags}
    <meta name="twitter:card" content="${image ? "summary_large_image" : "summary"}">
    <meta name="twitter:title" content="${escapeHtml(title)}">
    <meta name="twitter:description" content="${escapeHtml(description)}">
    <link rel="canonical" href="${canonical}">
    <link rel="icon" href="${prefix}assets/favicon.svg" type="image/svg+xml">
    <link rel="stylesheet" href="${prefix}styles.css">
    <link rel="stylesheet" href="${prefix}pages.css">
${extraHead}    <title>${escapeHtml(title)}</title>
  </head>
  <body class="subpage-body">
    <a class="skip-link" href="#main">Skip to content</a>
    ${header(prefix, current)}
    <main id="main" class="subpage-main">${body}</main>
    ${footer(prefix)}
  </body>
</html>
`;
}

