function collectionCard(collection, releases, prefix) {
  const covers = collection.releaseIds.slice(0, 3).map((id) => {
    const release = releases.find((candidate) => candidate.id === id);
    return release ? `<img src="${escapeHtml(release.artwork)}" alt="" width="160" height="160" loading="lazy">` : "";
  }).join("");

  return `<article class="collection-card">
    <div class="collection-covers" aria-hidden="true">${covers}</div>
    <p class="eyebrow">Curated collection</p>
    <h3>${escapeHtml(collection.title)}</h3>
    <p>${escapeHtml(collection.description)}</p>
    <a class="text-link" href="${prefix}music/collections/${collection.slug}/">Explore ${collection.releaseIds.length} ${collection.releaseIds.length === 1 ? "release" : "releases"} →</a>
  </article>`;
}

