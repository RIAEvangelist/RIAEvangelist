function validateCatalog(catalog) {
  const ids = new Set();
  const slugs = new Set();
  const landrUrls = new Set();
  const collectionSlugs = new Set(catalog.collections.map(({ slug }) => slug));
  if (catalog.releases.length !== 36) throw new Error(`Expected 36 releases, found ${catalog.releases.length}`);
  if (collectionSlugs.size !== catalog.collections.length) throw new Error("Duplicate collection slug");
  for (const release of catalog.releases) {
    if (ids.has(release.id)) throw new Error(`Duplicate release id: ${release.id}`);
    if (slugs.has(release.slug)) throw new Error(`Duplicate release slug: ${release.slug}`);
    if (landrUrls.has(release.landrUrl)) throw new Error(`Duplicate LANDR URL: ${release.landrUrl}`);
    if (!/^\d{12}$/.test(release.id)) throw new Error(`Invalid release id: ${release.id}`);
    if (!/^[a-z0-9]+(?:-[a-z0-9]+)*$/.test(release.slug)) throw new Error(`Invalid release slug: ${release.slug}`);
    if (release.landrUrl !== `https://artists.landr.com/${release.id}`) throw new Error(`Mismatched LANDR URL: ${release.id}`);
    if (!release.title?.trim() || !release.artist?.trim() || !release.summary?.trim()) throw new Error(`Incomplete release: ${release.id}`);
    if (!/^(Single|EP|Album)$/.test(release.type)) throw new Error(`Invalid release type: ${release.id}/${release.type}`);
    if (!/^\d{4}-\d{2}-\d{2}$/.test(release.releaseDate)) throw new Error(`Invalid release date: ${release.id}`);
    ids.add(release.id);
    slugs.add(release.slug);
    landrUrls.add(release.landrUrl);
    if (!/^https:\/\//.test(release.artwork) || !/^https:\/\//.test(release.landrUrl)) throw new Error(`Unsafe release URL: ${release.id}`);
    const serviceUrls = new Set();
    for (const link of release.services) {
      if (!serviceDefinitions[link.service]) throw new Error(`Unknown service: ${release.id}/${link.service}`);
      if (!/^https:\/\//.test(link.url)) throw new Error(`Unsafe service URL: ${release.id}/${link.service}`);
      if (serviceUrls.has(link.url)) throw new Error(`Duplicate service URL: ${release.id}/${link.url}`);
      serviceUrls.add(link.url);
    }
    for (const slug of release.collectionSlugs) if (!collectionSlugs.has(slug)) throw new Error(`Unknown collection ${slug} on ${release.id}`);
  }
  for (const collection of catalog.collections) {
    for (const id of collection.releaseIds) if (!ids.has(id)) throw new Error(`Unknown release ${id} in collection ${collection.slug}`);
  }
}

async function writePage(relativePath, html, generated, drift) {
  const destination = path.join(ROOT, relativePath);
  generated.push(relativePath.replaceAll("\\", "/"));
  if (CHECK_MODE) {
    const existing = await readFile(destination, "utf8").catch(() => null);
    if (existing !== html) drift.push(relativePath);
    return;
  }
  await mkdir(path.dirname(destination), { recursive: true });
  const existing = await readFile(destination, "utf8").catch(() => null);
  if (existing !== html) await writeFile(destination, html, "utf8");
}

async function removeStalePages(previous, generated) {
  const keep = new Set(generated);
  for (const relativePath of previous.filter((item) => !keep.has(item))) {
    const destination = path.resolve(ROOT, relativePath);
    if (!destination.startsWith(`${MUSIC_ROOT}${path.sep}`) || path.basename(destination) !== "index.html") {
      throw new Error(`Refusing to remove unsafe generated path: ${relativePath}`);
    }
    const contents = await readFile(destination, "utf8").catch(() => "");
    if (!contents.startsWith(GENERATED_MARKER)) throw new Error(`Refusing to remove unmarked page: ${relativePath}`);
    await rm(destination);
    const parent = path.dirname(destination);
    if ((await readdir(parent)).length === 0) await rm(parent, { recursive: false });
  }
}

async function main() {
  const catalog = JSON.parse(await readFile(path.join(ROOT, "data", "music.json"), "utf8"));
  validateCatalog(catalog);
  catalog.releases.sort((left, right) => right.releaseDate.localeCompare(left.releaseDate) || left.title.localeCompare(right.title));
  const generated = [];
  const drift = [];

  await writePage("music/index.html", musicHub(catalog), generated, drift);
  const pageCount = Math.max(1, Math.ceil(catalog.releases.length / PAGE_SIZE));
  for (let page = 1; page <= pageCount; page += 1) {
    const result = releasesPage(catalog, page);
    const output = page === 1 ? "music/releases/index.html" : `music/releases/page/${page}/index.html`;
    await writePage(output, result.html, generated, drift);
  }
  await writePage("music/collections/index.html", collectionsIndex(catalog), generated, drift);
  for (const release of catalog.releases) await writePage(`music/releases/${release.slug}/index.html`, releasePage(release), generated, drift);
  for (const collection of catalog.collections) await writePage(`music/collections/${collection.slug}/index.html`, collectionPage(collection, catalog), generated, drift);

  const manifestPath = path.join(MUSIC_ROOT, ".generated-pages.json");
  const manifest = `${JSON.stringify({ generated }, null, 2)}\n`;
  if (CHECK_MODE) {
    if (await readFile(manifestPath, "utf8").catch(() => null) !== manifest) drift.push("music/.generated-pages.json");
    if (drift.length) throw new Error(`Generated music pages are stale:\n${drift.map((item) => `- ${item}`).join("\n")}`);
    console.log(`Verified ${generated.length} music pages for ${catalog.releases.length} releases.`);
    return;
  }
  const previous = JSON.parse(await readFile(manifestPath, "utf8").catch(() => "{\"generated\":[]}"));
  await removeStalePages(previous.generated ?? [], generated);
  await mkdir(MUSIC_ROOT, { recursive: true });
  if (await readFile(manifestPath, "utf8").catch(() => null) !== manifest) await writeFile(manifestPath, manifest, "utf8");
  console.log(`Generated ${generated.length} music pages for ${catalog.releases.length} releases.`);
}

await main();
